import { jsPDF } from 'jspdf';
import type { InvestigationCase, Language } from '../types/geoint';
import { formatCoordPair } from './geoMath';

function classifyLabel(classification: InvestigationCase['ambiguity']['classification'], lang: Language): string {
  const map: Record<InvestigationCase['ambiguity']['classification'], { en: string; 'pt-PT': string }> = {
    gps_metadata: {
      en: 'EXIF GPS METADATA EXTRACTED (Device-reported coordinates)',
      'pt-PT': 'METADADOS GPS EXIF EXTRAÍDOS (Coordenadas reportadas pelo dispositivo)',
    },
    evidence_corroborated: {
      en: 'VISUAL MODEL ESTIMATE + CORROBORATED BY SECONDARY EVIDENCE',
      'pt-PT': 'ESTIMATIVA VISUAL CORROBORADA POR EVIDÊNCIA SECUNDÁRIA',
    },
    visual_estimate: {
      en: 'UNVERIFIED VISUAL COMPUTER-VISION ESTIMATE (Hypothesis only)',
      'pt-PT': 'ESTIMATIVA VISUAL DE VISÃO COMPUTACIONAL NÃO VERIFICADA (Apenas hipótese)',
    },
    inconclusive: {
      en: 'INCONCLUSIVE — INSUFFICIENT GEOGRAPHIC SIGNAL',
      'pt-PT': 'INCONCLUSIVO — SINAL GEOGRÁFICO INSUFICIENTE',
    },
  };
  return map[classification][lang];
}

export async function generateInvestigationReportPdf(params: {
  caseData: InvestigationCase;
  imageDataUrl?: string;
  mapSnapshotDataUrl?: string;
  lang: Language;
}): Promise<void> {
  const { caseData, imageDataUrl, mapSnapshotDataUrl, lang } = params;
  const pt = lang === 'pt-PT';
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const margin = 15;
  const contentW = pageW - margin * 2;
  let y = 16;

  const ensureSpace = (neededMm: number) => {
    if (y + neededMm > 276) {
      doc.addPage();
      y = 18;
    }
  };

  // Header band
  doc.setFillColor(10, 14, 22);
  doc.rect(0, 0, pageW, 28, 'F');
  doc.setTextColor(243, 245, 248);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('CRIMNEX GEOINT', margin, 12);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(154, 164, 178);
  doc.text(
    pt
      ? 'RELATÓRIO DE INVESTIGAÇÃO GEOESPACIAL — PROCESSAMENTO LOCAL'
      : 'GEOSPATIAL INTELLIGENCE INVESTIGATION REPORT — LOCAL PROCESSING',
    margin,
    18
  );
  doc.text(`geo.crimnex.com  |  ID: ${caseData.caseId}`, margin, 23);

  y = 36;

  // Classification banner
  const isGps = caseData.ambiguity.classification === 'gps_metadata';
  const isInconc = caseData.ambiguity.classification === 'inconclusive';
  if (isGps) {
    doc.setFillColor(16, 65, 48);
    doc.setTextColor(167, 243, 208);
  } else if (isInconc) {
    doc.setFillColor(72, 24, 28);
    doc.setTextColor(254, 202, 202);
  } else {
    doc.setFillColor(68, 45, 14);
    doc.setTextColor(253, 230, 138);
  }
  doc.rect(margin, y, contentW, 10, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.text(classifyLabel(caseData.ambiguity.classification, lang), margin + 3, y + 6.3);
  y += 15;

  // Forensic notice
  doc.setTextColor(60, 68, 82);
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(7.8);
  const disclaimer = pt
    ? 'AVISO METODOLÓGICO: As hipóteses visuais produzidas por modelos de IA constituem estimativas exploratórias e NÃO representam prova pericial conclusiva nem precisão métrica garantida. Apenas coordenadas derivadas de EXIF verificável ou confirmadas por fontes independentes devem ser tratadas como evidência direta.'
    : 'METHODOLOGICAL NOTICE: Visual predictions generated by AI models are exploratory geographic hypotheses and MUST NOT be interpreted as conclusive forensic proof or calibrated metric precision. Only independently verified evidence or authentic device GPS metadata should be treated as corroborated location evidence.';
  const discLines = doc.splitTextToSize(disclaimer, contentW);
  doc.text(discLines, margin, y);
  y += discLines.length * 3.8 + 4;

  // Section 1: Subject Image & Integrity
  ensureSpace(58);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.setTextColor(15, 23, 42);
  doc.text(pt ? '1. IDENTIFICAÇÃO E INTEGRIDADE DO FICHEIRO' : '1. SUBJECT FILE IDENTIFICATION & INTEGRITY', margin, y);
  y += 5;
  doc.setDrawColor(210, 215, 224);
  doc.line(margin, y, margin + contentW, y);
  y += 5;

  const textStartX = imageDataUrl ? margin + 52 : margin;
  const textMaxW = imageDataUrl ? contentW - 52 : contentW;

  if (imageDataUrl) {
    try {
      const ratio = caseData.imageValidation.aspectRatio || 1.33;
      const boxW = 46;
      const boxH = Math.min(42, boxW / ratio);
      doc.addImage(imageDataUrl, 'JPEG', margin, y, boxW, boxH);
    } catch {
      // ignore image draw errors
    }
  }

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(30, 41, 59);
  const metaRows = [
    `${pt ? 'Ficheiro' : 'File'}: ${caseData.imageValidation.fileName}`,
    `${pt ? 'Data da Análise' : 'Analysis UTC'}: ${caseData.createdAtIso}`,
    `${pt ? 'Dimensões / Assinatura' : 'Dimensions / Format'}: ${caseData.imageValidation.width} × ${caseData.imageValidation.height} px  (${caseData.imageValidation.detectedSignature})`,
    `${pt ? 'Tamanho' : 'Size'}: ${(caseData.imageValidation.fileSizeBytes / 1024).toFixed(1)} KB`,
    `SHA-256: ${caseData.imageValidation.sha256}`,
    `${pt ? 'Modelo Visual' : 'Visual Model'}: ${caseData.modelInfo.modelId} (${caseData.modelInfo.dtype}, ${caseData.modelInfo.executionProvider.toUpperCase()})`,
  ];
  for (const row of metaRows) {
    const wrapped = doc.splitTextToSize(row, textMaxW);
    doc.text(wrapped, textStartX, y);
    y += wrapped.length * 4.2;
  }
  y = Math.max(y, 118);

  // Section 2: Metadata Observed
  ensureSpace(32);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.setTextColor(15, 23, 42);
  doc.text(pt ? '2. METADADOS EXIF / ÓTICOS OBSERVADOS' : '2. OBSERVED EXIF & DEVICE METADATA', margin, y);
  y += 5;
  doc.line(margin, y, margin + contentW, y);
  y += 5;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  const m = caseData.metadata;
  const exifSummary = [
    `EXIF Present: ${m.hasExif ? `${m.rawTagsCount} tags` : 'None'}  |  GPS Embedded: ${m.hasGps && m.gps ? `YES (${formatCoordPair(m.gps.lat, m.gps.lon)})` : 'NO'}`,
    `Device: ${[m.cameraMake, m.cameraModel, m.lensModel].filter(Boolean).join(' · ') || 'Not present'}`,
    `Timestamp: ${m.dateTimeOriginal || 'Not present'}  |  Optics: ${m.focalLengthMm ? `${m.focalLengthMm}mm` : '—'}  f/${m.fNumber || '—'}  ISO ${m.iso || '—'}`,
  ];
  for (const row of exifSummary) {
    const lines = doc.splitTextToSize(row, contentW);
    doc.text(lines, margin, y);
    y += lines.length * 4.2;
  }
  y += 4;

  // Section 3: Candidate Hypotheses
  ensureSpace(55);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.text(pt ? '3. HIPÓTESES GEOGRÁFICAS CANDIDATAS' : '3. CANDIDATE GEOGRAPHIC HYPOTHESES', margin, y);
  y += 5;
  doc.line(margin, y, margin + contentW, y);
  y += 5;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.3);
  if (caseData.hypotheses.length === 0) {
    doc.text(pt ? 'Nenhuma hipótese suficientemente fundamentada.' : 'No sufficiently grounded geographic hypotheses.', margin, y);
    y += 6;
  } else {
    for (const h of caseData.hypotheses) {
      ensureSpace(16);
      const placeStr = h.nearestPlace
        ? `${h.nearestPlace.name}, ${h.nearestPlace.region ? h.nearestPlace.region + ', ' : ''}${h.nearestPlace.countryName} (${h.nearestPlace.distanceKm} km ${h.nearestPlace.compass})`
        : 'Remote / oceanic region';
      const sourceTag =
        h.source === 'exif_gps'
          ? '[EXIF GPS]'
          : h.source === 'manual_override'
            ? '[INVESTIGATOR VERIFIED]'
            : h.source === 'ocr_gazetteer'
              ? '[OCR GAZETTEER TOPONYM LEAD]'
              : `[VISUAL CLUSTER • ${(h.relativeAffinity * 100).toFixed(1)}% rel. share]`;

      doc.setFont('helvetica', 'bold');
      doc.text(`#${h.rank}  ${formatCoordPair(h.lat, h.lon)}   ${sourceTag}`, margin, y);
      y += 4;
      doc.setFont('helvetica', 'normal');
      doc.text(`    ${placeStr}  |  lat=${h.lat.toFixed(5)}, lon=${h.lon.toFixed(5)}`, margin, y);
      y += 4.2;
      if (h.solarCheck) {
        doc.text(
          `    Solar: Alt ${h.solarCheck.sunAltitudeDeg}° · Sun Az ${h.solarCheck.sunAzimuthDeg}° · Expected Shadow ${h.solarCheck.expectedShadowDirectionDeg}° (${h.solarCheck.consistencyLabel})`,
          margin,
          y
        );
        y += 4.2;
      }
      if (h.corroborationNotes.length > 0) {
        doc.text(`    Evidence: ${h.corroborationNotes.join(' ; ')}`, margin, y);
        y += 4.2;
      }
      y += 2;
    }
  }

  // Optional Map Snapshot
  if (mapSnapshotDataUrl) {
    try {
      const props = doc.getImageProperties(mapSnapshotDataUrl);
      const ratio = props.width && props.height ? props.width / props.height : 1.65;
      const maxH = 82;
      let drawW = contentW;
      let drawH = drawW / ratio;
      if (drawH > maxH) {
        drawH = maxH;
        drawW = drawH * ratio;
      }
      ensureSpace(drawH + 14);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10.5);
      doc.text(pt ? '4. REPRESENTAÇÃO CARTOGRÁFICA' : '4. CARTOGRAPHIC VISUALIZATION', margin, y);
      y += 5;
      const fmt = mapSnapshotDataUrl.startsWith('data:image/png') ? 'PNG' : 'JPEG';
      doc.addImage(mapSnapshotDataUrl, fmt, margin, y, drawW, drawH);
      y += drawH + 6;
    } catch {
      // skip if canvas tainted
    }
  }

  // Section 5: Complementary Evidence & Investigator Notes
  ensureSpace(45);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.text(pt ? '5. EVIDÊNCIAS COMPLEMENTARES & NOTAS DO INVESTIGADOR' : '5. COMPLEMENTARY EVIDENCE & INVESTIGATOR NOTES', margin, y);
  y += 5;
  doc.line(margin, y, margin + contentW, y);
  y += 5;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.4);
  const ocrLine =
    caseData.ocr.status === 'complete'
      ? `OCR (${caseData.ocr.language}): "${caseData.ocr.rawText.slice(0, 260) || 'No legible text detected'}"`
      : `OCR: Not executed (${caseData.ocr.status})`;
  const ocrWrapped = doc.splitTextToSize(ocrLine, contentW);
  doc.text(ocrWrapped, margin, y);
  y += ocrWrapped.length * 4.2 + 2;

  if (caseData.culturalClues?.length) {
    ensureSpace(20);
    for (const clue of caseData.culturalClues) {
      const line = pt
        ? `Pista cultural exploratória: ${clue.label}. ${clue.association} Afinidade relativa ${(clue.score * 100).toFixed(1)}% (não é probabilidade nem geolocalização).`
        : `Exploratory cultural cue: ${clue.label}. ${clue.association} Relative label affinity ${(clue.score * 100).toFixed(1)}% (neither probability nor geolocation evidence).`;
      const wrapped = doc.splitTextToSize(line, contentW);
      ensureSpace(Math.max(12, wrapped.length * 4.2 + 2));
      doc.text(wrapped, margin, y);
      y += wrapped.length * 4.2 + 2;
    }
  }

  if (caseData.ambiguity.reasons.length > 0) {
    const ambText = `${pt ? 'Avaliação de Ambiguidade' : 'Ambiguity Notes'}: ${caseData.ambiguity.reasons.join(' | ')}`;
    const ambLines = doc.splitTextToSize(ambText, contentW);
    doc.text(ambLines, margin, y);
    y += ambLines.length * 4.2 + 2;
  }

  const notes = caseData.investigatorNotes.trim() || (pt ? 'Sem notas adicionais registadas.' : 'No investigator notes recorded.');
  const noteLines = doc.splitTextToSize(`${pt ? 'Observações' : 'Investigator Notes'}: ${notes}`, contentW);
  doc.text(noteLines, margin, y);
  y += noteLines.length * 4.2 + 4;

  // Section 6: Technical Limitations & Attribution
  ensureSpace(34);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text(pt ? '6. METODOLOGIA E LIMITAÇÕES TÉCNICAS' : '6. METHODOLOGY & TECHNICAL LIMITATIONS', margin, y);
  y += 5;
  doc.line(margin, y, margin + contentW, y);
  y += 5;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.8);
  const limText = pt
    ? '1) Inferência visual executada localmente no navegador via GeoCLIP (ViT-Large/14 + LocationEncoder) sobre uma galeria de 100.000 coordenadas globais com agrupamento espacial (DBSCAN/NMS radial) e refinamento contínuo local. 2) A pontuação relativa do modelo reflete afinidade de embedding e NÃO constitui probabilidade estatística calibrada. 3) Interiores, imagens sem horizonte/arquitetura distintiva ou regiões sub-representadas nos dados de treino produzem elevada ambiguidade ou rejeição inconclusiva. 4) Dados cartográficos: © OpenFreeMap / OpenMapTiles / OpenStreetMap contributors (ODbL); Gazetteer: GeoNames (CC-BY 4.0).'
    : '1) Visual inference executed 100% locally in-browser via GeoCLIP (ViT-Large/14 + LocationEncoder) against a 100,000-point global coordinate gallery with spatial clustering and continuous local coordinate refinement. 2) Relative model affinity reflects embedding similarity and is NOT a calibrated statistical probability or metric confidence interval. 3) Indoor scenes, generic textures, or regions sparse in training imagery yield high ambiguity or inconclusive classification. 4) Cartography: © OpenFreeMap / OpenMapTiles / OpenStreetMap contributors (ODbL); Gazetteer: GeoNames (CC-BY 4.0).';
  const limLines = doc.splitTextToSize(limText, contentW);
  doc.text(limLines, margin, y);

  doc.save(`CRIMNEX-GEOINT-${caseData.caseId}.pdf`);
}
